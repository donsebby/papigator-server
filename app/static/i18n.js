/* Papigator Web – Oberflächensprache Deutsch/Englisch, ohne Build-Schritt.
   Der deutsche Text ist der Schlüssel (der Code bleibt lesbar), EN unten liefert die englische Fassung.
   - tr("Gespeichert") · tr("{n} Dokumente eingereiht", { n }) – Platzhalter in geschweiften Klammern
   - trn(n, "ein Dokument", "{n} Dokumente") – Einzahl/Mehrzahl, {n} ist die Zahl im Format der Sprache
   - Gleich geschriebene Wörter mit anderer Bedeutung: tr("Ordner|pl") (Zusatz nach |, Deutsch ohne Zusatz),
     in index.html data-i18n="Ordner|pl" am Element (ersetzt dessen ganzen Text)
   - index.html: Textknoten und die Attribute placeholder/title/aria-label/alt werden beim Laden ersetzt,
     wenn ihr Text (Leerraum zusammengefasst) als Schlüssel in EN steht. Absätze mit Auszeichnung
     (<b>, <a> …) tragen data-i18n-html: dann ist ihr innerHTML der Schlüssel und der Wert HTML.
   Fehlt eine Übersetzung, bleibt der deutsche Text stehen. tests/test_i18n.py prüft, dass jeder Schlüssel
   aus app.js und index.html hier steht. Sprache: Einstellungen → Darstellung (bl.lang), sonst die erste
   bevorzugte Browsersprache („de…“ → Deutsch, alles andere → Englisch). */
const LANG = (() => {
  let v = null;
  try { v = localStorage.getItem("bl.lang"); } catch {}
  if (v === "de" || v === "en") return v;
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || "de";
  return l.toLowerCase().startsWith("de") ? "de" : "en";
})();
// Silbentrennung und Vorlesen nach der Oberflächensprache (index.html steht fest auf lang="de")
document.documentElement.lang = LANG;
// Zahlen, Beträge, Monatsnamen: Deutsch immer de-DE; Englisch im Format des Browsers, wenn der Englisch spricht
const LOC = LANG === "de" ? "de-DE" : (() => {
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || "";
  return l.toLowerCase().startsWith("en") ? l : "en-US";
})();
document.documentElement.lang = LANG;

function tr(s, vars) {
  // „Ordner|pl“: Zusatz nach | trennt gleich geschriebene Wörter (Ordner/Folder vs. Folders); Deutsch ohne Zusatz
  let r = LANG === "en" && Object.prototype.hasOwnProperty.call(EN, s) ? EN[s] : s.replace(/\|[\w-]+$/, "");
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return r;
}
function trn(n, one, other, vars) {
  return tr(n === 1 ? one : other, { ...vars, n: Number(n).toLocaleString(LOC) });
}

function translateDom(root) {
  if (LANG === "de") return;
  const norm = (s) => s.replace(/\s+/g, " ").trim();
  // data-i18n="Schlüssel|zusatz": ganzer Text des Elements über einen ausdrücklichen Schlüssel (gleich geschriebene Wörter)
  for (const el of root.querySelectorAll("[data-i18n]")) {
    const k = el.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(EN, k)) el.textContent = EN[k];
  }
  for (const el of root.querySelectorAll("[data-i18n-html]")) {
    const k = norm(el.innerHTML);
    if (Object.prototype.hasOwnProperty.call(EN, k)) el.innerHTML = EN[k];
  }
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement.closest("script,style,[data-i18n],[data-i18n-html],[data-i18n-skip]")
      ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const k = norm(n.nodeValue);
    if (k && Object.prototype.hasOwnProperty.call(EN, k)) {
      const m = /^(\s*)[\s\S]*?(\s*)$/.exec(n.nodeValue);
      n.nodeValue = m[1] + EN[k] + m[2];
    }
  }
  for (const a of ["placeholder", "title", "aria-label", "alt"])
    for (const el of root.querySelectorAll(`[${a}]`)) {
      const k = norm(el.getAttribute(a));
      if (k && Object.prototype.hasOwnProperty.call(EN, k)) el.setAttribute(a, EN[k]);
    }
}

